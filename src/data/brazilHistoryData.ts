export interface IndicatorStatResult {
  currentValue: number;
  prevValue: number | null;
  changeAbs: number | null;
  changePercent: number | null;
  isPositiveForSociety: boolean | null; // true if the change is beneficial
  isUnchanged: boolean;
}

export function computeIndicatorStats(
  indicator: IndicatorMeta,
  currentYear: YearRecord,
  allYears: YearRecord[]
): IndicatorStatResult {
  const currentIndex = allYears.findIndex((y) => y.year === currentYear.year);
  const currentValue = currentYear.metrics[indicator.id as keyof typeof currentYear.metrics];

  if (currentIndex <= 0) {
    return {
      currentValue,
      prevValue: null,
      changeAbs: null,
      changePercent: null,
      isPositiveForSociety: null,
      isUnchanged: false,
    };
  }

  const prevYear = allYears[currentIndex - 1];
  const prevValue = prevYear.metrics[indicator.id as keyof typeof prevYear.metrics];

  const changeAbs = currentValue - prevValue;
  const changePercent = prevValue !== 0 ? ((currentValue - prevValue) / Math.abs(prevValue)) * 100 : 0;
  const isUnchanged = Math.abs(changePercent) < 0.05;

  let isPositiveForSociety: boolean | null = null;
  if (!isUnchanged) {
    if (indicator.betterDirection === 'higher') {
      isPositiveForSociety = changeAbs > 0;
    } else {
      isPositiveForSociety = changeAbs < 0;
    }
  }

  return {
    currentValue,
    prevValue,
    changeAbs,
    changePercent,
    isPositiveForSociety,
    isUnchanged,
  };
}
